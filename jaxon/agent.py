from .tools import Tool, build_tools, run_tool

log = logging.getLogger("jaxon")

CEO_SYSTEM = """You are Jaxon Vale, the AI CEO of this company and a partner to its founder.

You run the business day to day with the founder: you set direction, make calls, keep everyone accountable, and protect the company's cash and focus. You report to the founder, who has final say on anything irreversible (signing contracts, hiring or firing, spending large amounts, fundraising terms). On everything else, act.

How you work:
- You have persistent memory and a company operating system (tasks, decisions, goals/OKRs, KPIs, finances). Use them. Check memory before answering anything that depends on history. When you learn something durable — about the company, customers, people, the founder's preferences — save it with `remember` without being asked.
- Turn talk into action: when something needs doing, create a task with an owner and a due date. When a real decision is made, log it with the rationale.
- You lead a team of department heads you can brief with `delegate`: CFO (finance, pricing, fundraising), CMO (marketing, growth, brand), CTO (product engineering, architecture, technical risk), COO (operations, hiring, process), CPO (product strategy, roadmap, users), Counsel (legal and compliance risk — not a substitute for a licensed lawyer). Delegate when a question needs specialist depth; brief them on several in parallel when a decision cuts across functions; then make the call yourself.
- Use web search for current market, competitor, or regulatory facts. Cite what you found.
- Be direct. Lead with the answer or the decision, then the reasoning, then the next actions. Give a recommendation, not a menu. Push back when the founder is wrong, with reasons. Never invent numbers — if data is missing, say so and say how to get it.
- Keep responses tight. Use short headers or bullets only when they help.

Each user turn starts with a [Company snapshot] block generated by the system with the latest state; treat it as current fact. If the company profile is empty, your first job is to learn the business: ask the founder the few questions you need and save the answers."""


@dataclass
class TurnResult:
    text: str
    tool_calls: list[dict[str, Any]] = field(default_factory=list)
    stop_reason: str | None = None
    usage: dict[str, int] = field(default_factory=dict)


def _block_dicts(content: list[Any]) -> list[dict[str, Any]]:
    out = []
    for b in content:
        if isinstance(b, dict):
            out.append(b)
        elif hasattr(b, "to_dict"):
            out.append(b.to_dict())
        else:
            out.append(json.loads(b.model_dump_json()))
    return out


def _attr(block: Any, name: str, default: Any = None) -> Any:
    return block.get(name, default) if isinstance(block, dict) else getattr(block, name, default)


def run_loop(llm: LLM, *, system: str, messages: list[dict[str, Any]], tools: dict[str, Tool],
             extra_tools: list[dict[str, Any]] | None = None, effort: str | None = None,
             max_rounds: int = 25, on_event: Callable[[str, dict[str, Any]], None] | None = None) -> TurnResult:
    """Run the tool-use loop until the model ends its turn. Appends to `messages` in place."""
    definitions = [t.definition() for t in tools.values()] + list(extra_tools or [])
    calls: list[dict[str, Any]] = []
    usage = {"input_tokens": 0, "output_tokens": 0, "cache_read_input_tokens": 0}
    emit = on_event or (lambda kind, data: None)

    for _ in range(max_rounds):
        response = llm.call(system=system, messages=messages, tools=definitions, effort=effort)
        u = getattr(response, "usage", None)
        for k in usage:
            usage[k] += int(getattr(u, k, 0) or 0) if u is not None else 0
        content = _block_dicts(response.content)
        messages.append({"role": "assistant", "content": content})
        stop = response.stop_reason

        for b in content:
            if b.get("type") == "server_tool_use":
                emit("search", {"query": (b.get("input") or {}).get("query", "")})

        if stop == "refusal":
            return TurnResult("I can't help with that request.", calls, stop, usage)
        if stop == "pause_turn":
            continue
        if stop == "max_tokens":
            text = _text(content)
            return TurnResult(text + "\n\n[Response was cut off at the length limit.]", calls, stop, usage)
        if stop != "tool_use":
            return TurnResult(_text(content), calls, stop, usage)

        results = []
        for b in content:
            if b.get("type") != "tool_use":
                continue
            emit("tool", {"name": b["name"], "input": b.get("input")})
            output, is_error = run_tool(tools, b["name"], b.get("input"))
            calls.append({"name": b["name"], "input": b.get("input"), "error": is_error})
            results.append({"type": "tool_result", "tool_use_id": b["id"], "content": output, "is_error": is_error})
        messages.append({"role": "user", "content": results})

    return TurnResult(_text(messages[-1]["content"]) or "[Stopped: too many tool rounds.]", calls, "max_rounds", usage)


def _text(content: Any) -> str:
    if isinstance(content, str):
        return content
    return "\n".join(_attr(b, "text", "") for b in content if _attr(b, "type") == "text").strip()


class Jaxon:
    """The CEO agent. Holds memory, tools and department heads; conversations persist per session."""

    def __init__(self, config: Config | None = None, memory: Memory | None = None, client: Any = None):
        from .departments import build_delegate_tool

        self.config = config or Config()
        self.memory = memory or Memory(self.config.db_path)
        self.llm = LLM(self.config, client)
        self.tools = build_tools(self.memory)
        delegate = build_delegate_tool(self)
        self.tools[delegate.name] = delegate
        self.server_tools = [WEB_SEARCH_TOOL] if self.config.web_search else []

    def chat(self, message: str, session_id: str | None = None,
             on_event: Callable[[str, dict[str, Any]], None] | None = None) -> tuple[str, TurnResult]:
        session_id = session_id or uuid.uuid4().hex[:12]
        messages = self.memory.load_session(session_id)
        snapshot = json.dumps(self.memory.snapshot(), default=str)
        messages.append({"role": "user", "content": [
            {"type": "text", "text": f"[Company snapshot]\n{snapshot}"},
            {"type": "text", "text": message},
        ]})
        try:
            result = run_loop(self.llm, system=CEO_SYSTEM, messages=messages, tools=self.tools,
                              extra_tools=self.server_tools, max_rounds=self.config.max_tool_rounds,
                              on_event=on_event)
        finally:
            # Save even if the API call failed mid-turn; history stays append-only.
            if messages and messages[-1]["role"] == "user" and not _is_tool_results(messages[-1]):
                messages.pop()  # drop the unanswered user turn so the session stays valid
            self.memory.save_session(session_id, _close_dangling(messages))
        return session_id, result

    def history(self, session_id: str) -> list[dict[str, str]]:
        """Human-readable transcript of a session."""
        out = []
        for msg in self.memory.load_session(session_id):
            if msg["role"] == "user":
                if _is_tool_results(msg):
                    continue
                texts = [b["text"] for b in msg["content"] if b.get("type") == "text"
                         and not b["text"].startswith("[Company snapshot]")]
                out.append({"role": "user", "text": "\n".join(texts)})
            else:
                text = _text(msg["content"])
                if text:
                    out.append({"role": "assistant", "text": text})
        return out


def _is_tool_results(msg: dict[str, Any]) -> bool:
    c = msg.get("content")
    return isinstance(c, list) and bool(c) and all(b.get("type") == "tool_result" for b in c)


def _close_dangling(messages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """If a turn ended on unanswered tool_use (e.g. API error), trim back to the last complete exchange."""
    while messages:
        last = messages[-1]
        if last["role"] == "assistant" and not any(b.get("type") == "tool_use" for b in last["content"]):
            break
        messages.pop()
    return messages
