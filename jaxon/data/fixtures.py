"""Deterministic SYNTHETIC OHLCV generator for tests and demos.

Output is NOT market data. Every file written here starts with a
'# SYNTHETIC TEST FIXTURE' header that the loader detects, and every report
built from it is watermarked. Results on this data say nothing about
profitability.
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path

import numpy as np
import pandas as pd

from ..calendar import TradingCalendar
from ..config import SessionConfig

HEADER = ("# SYNTHETIC TEST FIXTURE - generated by jaxon.data.fixtures (seed={seed}). "
          "NOT MARKET DATA. Do not use as evidence of profitability.")


def session_minutes(cal: TradingCalendar, start: dt.date, days: int, step_min: int) -> pd.DatetimeIndex:
    stamps = []
    d = start
    end = start + dt.timedelta(days=days)
    while d < end:
        s = cal.session_by_close_date(d)
        if s is not None:
            stamps.append(pd.date_range(s.open, s.close, freq=f"{step_min}min", inclusive="left"))
        d += dt.timedelta(days=1)
    return stamps[0].append(stamps[1:]) if stamps else pd.DatetimeIndex([], tz="UTC")


def generate(session: SessionConfig, start: str, days: int, step_min: int, seed: int,
             start_price: float = 100.0, vol_per_bar: float = 0.0012, tick: float = 0.01) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    cal = TradingCalendar(session)
    idx = session_minutes(cal, dt.date.fromisoformat(start), days, step_min)
    n = len(idx)
    drift = np.zeros(n)
    i = 0
    scale = step_min / 5.0
    while i < n:
        seg = int(rng.integers(int(36 / scale) + 1, int(220 / scale) + 2))
        kind = rng.random()
        if kind < 0.12:                                    # impulse leg (creates displacement candles)
            seg = int(rng.integers(max(2, int(4 / scale)), int(10 / scale) + 3))
            drift[i:i + seg] = rng.uniform(1.2, 2.2) * vol_per_bar
        elif kind < 0.55:                                  # grind up
            drift[i:i + seg] = rng.uniform(0.02, 0.12) * vol_per_bar
        else:                                              # pullback / chop
            drift[i:i + seg] = rng.uniform(-0.14, 0.02) * vol_per_bar
        i += seg
    vol = vol_per_bar * np.exp(rng.normal(0, 0.25, n))
    ret = drift + rng.normal(0, 1, n) * vol
    close = start_price * np.exp(np.cumsum(ret))
    open_ = np.r_[start_price, close[:-1]] * np.exp(rng.normal(0, 0.15, n) * vol)
    wick_hi = np.abs(rng.normal(0, 0.5, n)) * vol * close
    wick_lo = np.abs(rng.normal(0, 0.5, n)) * vol * close
    high = np.maximum(open_, close) + wick_hi
    low = np.minimum(open_, close) - wick_lo
    q = lambda x: np.round(np.round(x / tick) * tick, 8)
    open_, close = q(open_), q(close)
    high = np.maximum(q(high), np.maximum(open_, close))
    low = np.minimum(q(low), np.minimum(open_, close))
    volume = np.round(rng.lognormal(8, 0.5, n) * (1 + 3 * (drift > 1.0 * vol_per_bar)))
    return pd.DataFrame({"timestamp": idx.strftime("%Y-%m-%dT%H:%M:%SZ"), "open": open_, "high": high,
                         "low": low, "close": close, "volume": volume})


def write(df: pd.DataFrame, path: str | Path, seed: int) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as fh:
        fh.write(HEADER.format(seed=seed) + "\n")
        df.to_csv(fh, index=False)
    return path


