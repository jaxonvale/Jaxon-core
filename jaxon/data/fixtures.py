SCENARIO_HEADER = ("# SYNTHETIC SCRIPTED SCENARIO - hand-designed price path that walks through every strategy "
                   "stage (bias, zone, touch, shift, entry, exits). NOT MARKET DATA.")

# (hours from start, price). Times are chosen inside bars, not on bar edges, so swing points are strict.
_DAY5 = [(121.6, 117.5), (124.1, 117.0), (126.0, 114.0), (127.2, 115.6), (128.5, 112.5), (129.0, 112.2),
         (129.5, 116.0), (130.05, 116.6), (131.6, 112.8), (131.8, 113.3), (132.3, 112.35), (132.55, 113.45)]


def scenario_waypoints() -> list[tuple[float, float]]:
    w = [(0, 100.0), (18, 106.0), (30, 103.0), (50, 110.0), (62, 106.0), (82, 114.0), (94, 110.0),
         (110, 118.0), (120, 116.0)]
    w += _DAY5                                            # day 5: winning setup (VWAP target)
    w += [(133.5, 117.0), (134.6, 118.5), (144.0, 118.0)]
    w += [(t + 24, p + 2.0) for t, p in _DAY5]            # day 6: same shape, then the stop is hit
    w += [(156.8, 115.7), (157.5, 113.8), (159.0, 114.5), (192.0, 117.0)]
    return w


def _heavy(h: float) -> bool:
    """Heavy morning volume on days 5 and 6 puts session VWAP well above the later pullback."""
    return 120.0 <= h < 124.1 or 144.0 <= h < 148.1


def scenario(start: str = "2025-01-06", step_min: int = 5, tick: float = 0.01, wick: float = 0.01) -> pd.DataFrame:
    wp = scenario_waypoints()
    ts, ps = np.array([t for t, _ in wp]), np.array([p for _, p in wp])
    t0 = pd.Timestamp(start, tz="UTC")
    n = int(ts[-1] * 60 // step_min)
    rows = []
    for k in range(n):
        a, b = k * step_min / 60.0, (k + 1) * step_min / 60.0
        inside = ps[(ts > a) & (ts < b)]
        pa, pb = float(np.interp(a, ts, ps)), float(np.interp(b, ts, ps))
        hi = max([pa, pb, *inside]) + wick
        lo = min([pa, pb, *inside]) - wick
        q = lambda x: round(round(x / tick) * tick, 8)
        rows.append({"timestamp": (t0 + pd.Timedelta(minutes=k * step_min)).strftime("%Y-%m-%dT%H:%M:%SZ"),
                     "open": q(pa), "high": q(hi), "low": q(lo), "close": q(pb),
                     "volume": 6000.0 if _heavy(a) else 1000.0})
    return pd.DataFrame(rows)


def write_scenario(path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as fh:
        fh.write(SCENARIO_HEADER + "\n")
        scenario().to_csv(fh, index=False)
    return path


