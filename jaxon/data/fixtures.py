CRYPTO_SESSION = SessionConfig(timezone="UTC", open="00:00", close="24:00", trading_weekdays=list(range(7)))


def build_default_fixtures(out_dir: str | Path = "fixtures") -> list[Path]:
    out = Path(out_dir)
    eq = generate(EQUITY_SESSION, "2025-03-03", 120, 1, seed=11, start_price=100.0, vol_per_bar=0.0007)
    eq = eq.drop(eq.index[5000:5003])            # deliberate 3-minute intra-session gap (shows gap handling)
    cr = generate(CRYPTO_SESSION, "2025-01-01", 120, 5, seed=23, start_price=40000.0, vol_per_bar=0.0016, tick=0.1)
    return [write(eq, out / "SYNTHETIC_equity_1m.csv", 11), write(cr, out / "SYNTHETIC_crypto_5m.csv", 23),
            write_scenario(out / "SYNTHETIC_scenario_5m.csv")]




